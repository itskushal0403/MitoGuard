"""Tabulate MIDOG++ cases by scanner x tumor type (the "check first" step) -> docs/data_audit.md."""
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from mitoguard.data import IMPOSTER, MITOSIS, load_annotations, load_cases, make_folds  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    cases = load_cases()
    ann = load_annotations()
    raw = pd.read_csv(os.path.join(os.environ.get("MIDOG_ROOT", "/scratch/m25csa016/midogpp"), "datasets_xvalidation.csv"), sep=";")
    n_mit = ann[ann.label == MITOSIS].groupby("case_id").size()
    n_imp = ann[ann.label == IMPOSTER].groupby("case_id").size()
    cases = cases.assign(n_mit=n_mit.reindex(cases.case_id).fillna(0).to_numpy(),
                         n_imp=n_imp.reindex(cases.case_id).fillna(0).to_numpy())
    xt = pd.crosstab(cases.tumor, cases.scanner, margins=True)
    raw_xt = pd.crosstab(raw.Tumor, raw.Scanner)
    dom = cases.groupby(["tumor", "scanner", "origin", "species"]).agg(
        cases=("case_id", "size"), mitoses=("n_mit", "sum"), imposters=("n_imp", "sum"),
        mpp=("mpp", "median"), zero_mitosis_cases=("n_mit", lambda s: int((s == 0).sum()))).reset_index()
    # Cramer's V between scanner and tumor
    import numpy as np
    from scipy.stats import chi2_contingency
    tab = pd.crosstab(cases.tumor, cases.scanner)
    chi2 = chi2_contingency(tab)[0]
    v = np.sqrt(chi2 / (tab.values.sum() * (min(tab.shape) - 1)))
    folds = []
    for p in ("loto", "loso", "indomain"):
        for f in make_folds(p):
            folds.append({"protocol": p, "held_out": f.name, "train_cases": len(f.train), "val_cases": len(f.val),
                          "test_cases": len(f.test),
                          "test_mitoses": int(cases.loc[f.test, "n_mit"].sum())})
    lines = [
        "# MIDOG++ data audit",
        "",
        "Generated by `scripts/data_audit.py`.",
        "",
        "## Scanner x tumor type (official CSV, unmodified)",
        "",
        raw_xt.to_markdown(),
        "",
        "`Hamammatsu XR` (human breast cancer) and `Hamamatsu XR` (neuroendocrine tumour, melanoma) are the same",
        "device at the same lab (UMC Utrecht); the double 'm' is a typo in the metadata. After merging, MIDOG++",
        "contains **4 physical scanner models**.",
        "",
        "## Scanner x tumor type (merged)",
        "",
        xt.to_markdown(),
        "",
        f"Cramer's V between scanner and tumor type = **{v:.2f}** (1 = fully determined).",
        "Every tumour type except human breast cancer was digitised on exactly one scanner, and three scanners",
        "only ever saw one or two tumour types. Scanner and tumour type are therefore **strongly linked**: a",
        "leave-one-scanner-out split would mostly measure tumour-type shift. Following the project brief, the",
        "**primary protocol is leave-one-tumor-type-out (LOTO, 7 folds)** and leave-one-scanner-out (LOSO, 4",
        "folds) is reported as secondary. The only clean scanner-only comparison is human breast cancer, which",
        "was scanned on three devices (50 cases each); the LOSO folds for S360 (breast only) isolate pure",
        "scanner shift.",
        "",
        "## Domains",
        "",
        dom.to_markdown(index=False),
        "",
        f"Total: {len(cases)} cases, {int(cases.n_mit.sum())} mitotic figures, {int(cases.n_imp.sum())} imposters "
        f"(imposters outnumber mitoses {cases.n_imp.sum() / cases.n_mit.sum():.2f}:1). "
        f"{int((cases.n_mit == 0).sum())} regions contain no mitotic figure at all.",
        "",
        "Other metadata quirks: the official CSV lists the species of canine soft tissue sarcoma as `Human`",
        "(a metadata error; the tumour is canine), and `MIDOG++.json` lists 553 image ids of which only the 503",
        "in the CSV have files and labels (ids 151-200 are unlabelled and unused).",
        "",
        "## Folds",
        "",
        "Within every fold, 20% of the training-domain cases (stratified by domain) form a validation set used",
        "for all model selection, calibration and threshold tuning. The held-out domain is never used for tuning.",
        "",
        pd.DataFrame(folds).to_markdown(index=False),
        "",
    ]
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    open(os.path.join(ROOT, "docs", "data_audit.md"), "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
